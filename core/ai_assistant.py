    elim_info = signals_dict.get('elimination_info') or {}
    if elim_info.get('is_eliminated', False):
        for r in elim_info.get('reasons', []):
            if r not in cons:
                cons.append(r)

    # 檢查拉回幅度是否過深 (09/18 助教鐵律：正常漲10塊拉回2塊，底平或回撤過深非健康多頭)
    if sup and sup > 0 and abs(l - sup) / sup < 0.015 and not is_bull:
        cons.append(f"拉回幅度過深（低點接近前波底線 {sup:.2f} 元），非健康『漲10回2』的淺幅修正，型態偏向底平或直角三角，慎防轉弱破支撐！")

    # 檢查當日是否本身就是爆量黑K
    is_today_heavy_black = False
    if v_ma20 > 0 and v >= v_ma20 * 1.6 and (c < o or (h - max(o, c)) > (h - l) * 0.4):
        is_today_heavy_black = True
        cons.append(f"當日出現極端爆量長黑 K（成交量為 20 均量 {round(v/v_ma20, 1)} 倍，高點 {h:.2f} 元），主力高檔出貨套牢賣壓沉重！")

    # 檢查前方未化解的爆量黑K
    unresolved_black_ks = [b for b in heavy_black_ks if b['high'] >= c and b['full_date'] != last['Date'].strftime('%Y-%m-%d')]
