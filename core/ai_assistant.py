    if signals_dict.get('is_turnover_success', False):
        pros.append("【高檔巨量換手成功】高檔爆大量黑K或變盤線後，3天內強勢長紅過高，籌碼洗淨換手完畢續噴！")

    if signals_dict.get('is_attack_vol', False):
        pros.append("【5MA 攻擊量達標】今日量能達 5MA 基本量 1.25 倍以上，多方主力出量推升！")

    prev_high = float(prev['High'])
    if signals_dict.get('pullback_buy', False) or (is_stand_5ma and l <= sma5 * 1.02 and c > o):
        if is_break_yesterday:
            pros.append(f"符合『回後買上漲』進場確認（今日收盤 {c:.2f} 元突破前一日高點 {prev_high:.2f} 元，轉折紅 K 攻擊確立）")
        else:
            cons.append(f"處於『回後買上漲觀察位置』，但今日收盤尚未突破前一日高點 ({prev_high:.2f} 元)；依 09/18 助教鐵律：該高點點位固定不變，須等待後續收盤突破前一日高點才算正式進場！")

