    prev_sma20 = float(df.iloc[-2]['SMA_20']) if len(df) > 1 else sma20
    is_20ma_down = (sma20 < prev_sma20 * 0.999)
    if is_20ma_down and (c < sma20 or (c >= sma20 and not is_bull)):
        cons.append(f"月線 (20MA, {sma20:.2f} 元) 目前仍向下彎助跌；依 09/18 助教鐵律『月線下彎不能算 ABC 突破，只能視為空頭反彈』，上方反壓沉重！")

